import { afterEach, describe, expect, test } from 'bun:test'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import type { NamedIcon, Renderer } from './types.ts'

import { octaneRenderer } from './octane.ts'
import { reactRenderer } from './react.ts'
import { solidRenderer } from './solid.ts'
import { tsrxRenderer } from './tsrx.ts'

const icon = (name: string, pascal: string, d: string): NamedIcon => ({
	ref: { set: 'lucide', name },
	body: `<path d="${d}" />`,
	viewBox: '0 0 24 24',
	license: { spdx: 'ISC' },
	componentName: `Icon${pascal}`,
	attrs: { fill: 'none', stroke: 'currentColor', 'stroke-width': '2' },
	fileName: name,
})

// Distinct, greppable path data so tree-shaking is observable in a bundle.
const house = icon('house', 'House', 'M-HOUSE-PATH')
const menu = icon('menu', 'Menu', 'M-MENU-PATH')
const shell = icon('shell', 'Shell', 'M-SHELL-PATH') // lucide has an icon named "shell"

const byPath = (files: { path: string; content: string }[]) =>
	Object.fromEntries(files.map((f) => [f.path, f.content]))

describe.each([
	['react', reactRenderer],
	['solid', solidRenderer],
] as const)('%s renderModules', (_id, renderer: Renderer) => {
	const files = byPath(renderer.renderModules!([house, menu, shell]))

	test('emits a shell, one module per icon and a barrel', () => {
		expect(Object.keys(files).sort()).toEqual([
			'_shell.tsx',
			'house.tsx',
			'index.ts',
			'menu.tsx',
			'package.json',
			'shell.tsx',
		])
	})

	test('a package.json scopes sideEffects: false to the directory', () => {
		expect(JSON.parse(files['package.json']!)).toEqual({ sideEffects: false })
	})

	test('the shell file cannot collide with an icon named "shell"', () => {
		expect(files['_shell.tsx']).toContain('export const Icon = ')
		expect(files['shell.tsx']).toContain('export const IconShell')
	})

	test('an icon module exports only its component and imports the shell', () => {
		const content = files['house.tsx']!
		expect(content.startsWith('// Auto-generated by sigil')).toBe(true)
		expect(content).toContain("from './_shell'")
		expect(content).toContain('// lucide/house · ISC')
		expect(content).toContain('export const IconHouse = (props: IconProps)')
		expect(content).not.toContain('IconMenu')
	})

	test('the barrel is pure re-exports', () => {
		const barrel = files['index.ts']!
		expect(barrel).toContain("export { IconHouse } from './house'")
		expect(barrel).toContain("export { IconMenu } from './menu'")
		expect(barrel).toContain("export type { IconProps } from './_shell'")
		expect(barrel.split('\n').filter((l) => l && !l.startsWith('//'))).toEqual(
			expect.arrayContaining([expect.stringMatching(/^export /)]),
		)
		expect(barrel).not.toMatch(/^(const|let|var|function|import) /m)
	})
})

test('octane and tsrx have no per-icon layout', () => {
	expect(octaneRenderer.renderModules).toBeUndefined()
	expect(tsrxRenderer.renderModules).toBeUndefined()
})

describe('tree-shaking', () => {
	const dirs: string[] = []
	afterEach(() => {
		for (const dir of dirs.splice(0))
			rmSync(dir, { recursive: true, force: true })
	})

	test('importing one icon from the barrel drops every other icon', async () => {
		const dir = mkdtempSync(join(tmpdir(), 'sigil-shake-'))
		dirs.push(dir)
		const out = join(dir, 'icons')
		mkdirSync(out)
		for (const file of reactRenderer.renderModules!([house, menu, shell])) {
			writeFileSync(join(out, file.path), file.content)
		}
		writeFileSync(
			join(dir, 'entry.tsx'),
			"import { IconHouse } from './icons'\nconsole.log(IconHouse)\n",
		)
		const result = await Bun.build({
			entrypoints: [join(dir, 'entry.tsx')],
			minify: false,
			external: ['react', 'react/jsx-runtime', 'react/jsx-dev-runtime'],
		})
		expect(result.success).toBe(true)
		const code = await result.outputs[0]!.text()
		expect(code).toContain('M-HOUSE-PATH')
		expect(code).not.toContain('M-MENU-PATH')
		expect(code).not.toContain('M-SHELL-PATH')
	})
})
