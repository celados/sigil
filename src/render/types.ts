import type { CssMode, ResolvedIcon } from '../source/types.ts'

export type NamedIcon = ResolvedIcon & {
	componentName: string
	/**
	 * 根 <svg> 的 presentation 属性(fill/stroke/stroke-width…),已从 body 提升,
	 * 子元素只靠继承——CSS 写在 <svg> 上才能覆盖线宽。见 svg-attrs.ts。
	 */
	attrs: Record<string, string>
	/** 逐文件输出时的文件名(无扩展名),已保证唯一 */
	fileName: string
	/**
	 * Resolved source default or manifest override; required only by the CSS
	 * renderer.
	 */
	cssMode?: CssMode
}

/** Path 相对于输出目录;模块型 renderer 返回单文件,CLI 可用 -o 覆盖其位置 */
export type RenderedFile = { path: string; content: string }

export type RenderOptions = {
	readonly atlas?: boolean
	readonly atlasFileName?: string
	readonly atlasImportPath?: string
}

export interface Renderer {
	readonly id: string
	/** 模块型 renderer 的默认文件名;null 表示逐图标输出 */
	readonly defaultFile: string | null
	render(icons: NamedIcon[], options?: RenderOptions): RenderedFile[]
	/**
	 * One module per icon, a shared shell and a side-effect-free `index` barrel,
	 * so a bundler places each icon in the chunk that uses it. Absent when the
	 * target has no per-icon layout.
	 */
	renderModules?(icons: NamedIcon[]): RenderedFile[]
}

export const GENERATED_MARK = '// Auto-generated by sigil'

/** Shared by the per-icon layout of the jsx renderers. */
export const SHELL_FILE = '_shell'

/**
 * Scopes `sideEffects: false` to the generated directory. A barrel the bundler
 * must assume has side effects keeps every module it re-exports in each chunk
 * that imports it, which puts every icon back into one shared chunk (measured
 * with rolldown); the nearest package.json is how bundlers learn the modules
 * are pure.
 */
export const PACKAGE_FILE: RenderedFile = {
	path: 'package.json',
	content: '{ "sideEffects": false }\n',
}

export function renderBarrel(icons: NamedIcon[], ext: string): RenderedFile {
	const exports = icons
		.map((icon) => `export { ${icon.componentName} } from './${icon.fileName}'`)
		.join('\n')
	return {
		path: `index${ext}`,
		content: `${GENERATED_MARK} — do not edit. Run \`sigil etch\` to regenerate.\n\nexport type { IconProps } from './${SHELL_FILE}'\n${exports}\n`,
	}
}

/** 根属性 → ` fill="none" stroke-width="2"`;jsx 时转 React 风格的 camelCase */
export function rootAttrs(
	icon: NamedIcon,
	jsx = false,
	omit: readonly string[] = [],
): string {
	return Object.entries(icon.attrs)
		.filter(([name]) => !omit.includes(name))
		.map(([name, value]) => {
			const key = jsx
				? name.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())
				: name
			return ` ${key}="${value}"`
		})
		.join('')
}

export function licenseTag(icon: NamedIcon): string {
	const lic = icon.license?.spdx ?? icon.license?.title
	return lic ? ` · ${lic}` : ''
}
