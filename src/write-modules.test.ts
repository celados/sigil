import { afterEach, expect, test } from 'bun:test'
import {
	existsSync,
	mkdtempSync,
	readdirSync,
	rmSync,
	writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { writeModules } from './write-modules.ts'

const dirs: string[] = []
afterEach(() => {
	for (const dir of dirs.splice(0))
		rmSync(dir, { recursive: true, force: true })
})

test('re-etch removes stale generated files and keeps hand-written ones', () => {
	const dir = mkdtempSync(join(tmpdir(), 'sigil-write-'))
	dirs.push(dir)
	const generated = (name: string) => ({
		path: `${name}.tsx`,
		content: `// Auto-generated by sigil — do not edit.\nexport const ${name} = 1\n`,
	})
	writeModules(dir, [generated('a'), generated('b')])
	writeFileSync(join(dir, 'mine.tsx'), 'export const mine = 1\n')

	writeModules(dir, [generated('a')])

	expect(readdirSync(dir).sort()).toEqual(['a.tsx', 'mine.tsx'])
	expect(existsSync(join(dir, 'b.tsx'))).toBe(false)
})
